#!/usr/bin/env python3
"""Generate a self-contained browser replay from real simulator trajectories.

    python scripts/build_demo.py
    open docs/demo/index.html
"""
import argparse
import json
from pathlib import Path

from export_trajectory import build_trajectory_payload
from climbsim.route import Route

ROOT = Path(__file__).resolve().parents[1]


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("routes", nargs="*", type=Path)
    parser.add_argument("--output", type=Path, default=ROOT / "docs/demo/data.js")
    parser.add_argument("--timestep", type=float, default=0.002)
    parser.add_argument("--frame-every", type=int, default=20)
    args = parser.parse_args()
    paths = args.routes or sorted((ROOT / "data/routes/showcase").glob("*.json"))
    if not paths:
        parser.error("no routes found")
    payloads = []
    for path in paths:
        route = Route.from_json(path)
        payload = build_trajectory_payload(route, frame_every=args.frame_every, timestep=args.timestep)
        payload["id"] = path.stem
        payload["sourcePath"] = str(path.relative_to(ROOT)) if path.is_relative_to(ROOT) else str(path)
        raw = json.loads(path.read_text())
        payload["description"] = raw.get("description", "")
        payloads.append(payload)
        print(f"{route.name}: {'completed' if payload['success'] else 'not completed'}, "
              f"{len(payload['frames'])} frames")
        for outcome in payload["outcomes"]:
            print(f"  {outcome['phase']}: {outcome['reason']}")
    args.output.parent.mkdir(parents=True, exist_ok=True)
    # No fetch or remote dependency: file:// works offline. Escape HTML-sensitive
    # characters so the output is safe even if later embedded in a script tag.
    encoded = json.dumps(payloads, separators=(",", ":"), allow_nan=False)
    encoded = encoded.replace("<", "\\u003c").replace(">", "\\u003e").replace("&", "\\u0026")
    args.output.write_text("// Generated by scripts/build_demo.py. Do not edit.\nwindow.CLIMB_DEMOS=" + encoded + ";\n")
    print(f"Wrote {args.output}")


if __name__ == "__main__":
    main()
